/**
 * Stores keyboard input states.
 */
class Keyboard {
    /** @type {boolean} Left movement key */
    LEFT = false;

    /** @type {boolean} Right movement key */
    RIGHT = false;

    /** @type {boolean} Up movement key */
    UP = false;

    /** @type {boolean} Down movement key */
    DOWN = false;

    /** @type {boolean} Jump key */
    SPACE = false;

    /** @type {boolean} Action / attack key */
    KEY_D = false;
}