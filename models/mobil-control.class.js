/**
 * Stores mobile control input states.
 */
class MobilControl {
    /** @type {boolean} Left movement button */
    LEFT = false;

    /** @type {boolean} Right movement button */
    RIGHT = false;

    /** @type {boolean} Up movement button */
    UP = false;

    /** @type {boolean} Down movement button */
    DOWN = false;

    /** @type {boolean} Jump button */
    SPACE = false;

    /** @type {boolean} Action / attack button */
    KEY_D = false;
}